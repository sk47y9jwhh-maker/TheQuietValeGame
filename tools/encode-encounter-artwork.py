#!/usr/bin/env python3
"""Encode the web card frames from the approved trimmed artwork.

The sources (src/assets/encounter-cards/web/*.png) and the print files are
read-only. The web variants are high-quality lossy WebP: a card frame is a
background behind live text, and lossless files were 10 to 20 times larger,
so card text appeared seconds before its card. Needs Pillow.
"""
import hashlib, io, json, os
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = "src/assets/encounter-cards/web/responsive"
QUALITY = 86
TYPES = {"arrival": "arrival", "boon": "boon", "burden": "burden", "goldenBoon": "golden-boon"}

def sha(data):
    return hashlib.sha256(data).hexdigest()

def read(path):
    with open(os.path.join(ROOT, path), "rb") as handle:
        return handle.read()

entries, imports, definitions = {}, [], []
for kind, base in TYPES.items():
    source_path = f"src/assets/encounter-cards/web/{base}.png"
    print_path = f"src/assets/encounter-cards/{base}.png"
    source = read(source_path)
    image = Image.open(io.BytesIO(source))
    icc = image.info.get("icc_profile")
    rgb = image.convert("RGB")
    widths = sorted({min(420, rgb.width), min(840, rgb.width), rgb.width})
    variants = []
    for width in widths:
        height = round(rgb.height * width / rgb.width)
        resized = rgb if width == rgb.width else rgb.resize((width, height), Image.LANCZOS)
        buffer = io.BytesIO()
        options = {"quality": QUALITY, "method": 6}
        if icc:
            options["icc_profile"] = icc
        resized.save(buffer, "WEBP", **options)
        data = buffer.getvalue()
        name = f"{base}-{width}.webp"
        with open(os.path.join(ROOT, OUT, name), "wb") as handle:
            handle.write(data)
        variants.append({"path": f"{OUT}/{name}", "width": width, "height": height, "bytes": len(data), "sha256": sha(data), "fullSize": width == rgb.width})
        imports.append(f'import {kind}{width} from "./{name}";')
    entries[kind] = {
        "source": {"path": source_path, "width": rgb.width, "height": rgb.height, "bytes": len(source), "sha256": sha(source)},
        "print": {"path": print_path, "bytes": len(read(print_path)), "sha256": sha(read(print_path))},
        "variants": variants,
    }
    src_set = ", ".join(f'{kind}{w} + " {w}w"' for w in widths)
    definitions.append(f"  {kind}: {{ width: {rgb.width}, height: {rgb.height}, src: {kind}{widths[0]}, srcSet: [{src_set}].join(\", \") }}")
    print(kind, ", ".join(f"{v['width']}px {v['bytes'] // 1024} KB" for v in variants))

manifest = {"format": f"WebP, quality {QUALITY}", "resize": "Lanczos, aspect ratio retained, no enlargement", "encoder": "Pillow (tools/encode-encounter-artwork.py)", "entries": entries}
with open(os.path.join(ROOT, OUT, "manifest.json"), "w") as handle:
    handle.write(json.dumps(manifest, indent=2) + "\n")
with open(os.path.join(ROOT, OUT, "artwork.generated.ts"), "w") as handle:
    handle.write("// Generated by tools/encode-encounter-artwork.py. Preserve the approved sources.\n" + "\n".join(imports) + "\n\nexport const responsiveEncounterArtwork = {\n" + ",\n".join(definitions) + "\n} as const;\n")

// Re-encode the approved trimmed artwork. Originals and print exports are read-only.
// Optional tooling dependency: sharp 0.35.x (never loaded by the game or its build).
// QV_SHARP_MODULE may point to a preinstalled sharp module.
import { createHash } from "node:crypto";
import { createRequire } from "node:module";
import { readFile, mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const require = createRequire(import.meta.url);
let sharp;
try { sharp = require(process.env.QV_SHARP_MODULE || "sharp"); }
catch { throw new Error("Artwork encoding needs sharp. Install it for tooling, or set QV_SHARP_MODULE to a preinstalled module path."); }
const root = fileURLToPath(new URL("../", import.meta.url));
const output = "src/assets/encounter-cards/web/responsive";
await mkdir(path.join(root, output), { recursive: true });
const hash = (data) => createHash("sha256").update(data).digest("hex");
const entries = {};
const imports = [];
const definitions = [];
for (const [type, basename] of Object.entries({ arrival: "arrival", boon: "boon", burden: "burden", goldenBoon: "golden-boon" })) {
  const sourcePath = `src/assets/encounter-cards/web/${basename}.png`;
  const printPath = `src/assets/encounter-cards/${basename}.png`;
  const source = await readFile(path.join(root, sourcePath));
  const print = await readFile(path.join(root, printPath));
  const meta = await sharp(source).metadata();
  const widths = [...new Set([Math.min(420, meta.width), Math.min(840, meta.width), meta.width])].sort((a, b) => a - b);
  const originalPixels = await sharp(source).ensureAlpha().raw().toBuffer();
  const variants = [];
  for (const width of widths) {
    const resize = () => sharp(source).resize({ width, withoutEnlargement: true });
    const bytes = await resize().keepIccProfile().webp({ lossless: true, effort: 6 }).toBuffer();
    const expected = await resize().ensureAlpha().raw().toBuffer({ resolveWithObject: true });
    const decoded = await sharp(bytes).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
    if (!expected.data.equals(decoded.data) || expected.info.width !== decoded.info.width || expected.info.height !== decoded.info.height) {
      throw new Error(`${basename} at ${width}px did not preserve its decoded pixels.`);
    }
    if (width === meta.width && !originalPixels.equals(decoded.data)) throw new Error(`${basename} full-size pixels changed.`);
    const encodedMeta = await sharp(bytes).metadata();
    if (meta.icc && !meta.icc.equals(encodedMeta.icc)) throw new Error(`${basename} colour profile changed.`);
    const filename = `${basename}-${width}.webp`;
    const imagePath = `${output}/${filename}`;
    await writeFile(path.join(root, imagePath), bytes);
    variants.push({ path: imagePath, width, height: decoded.info.height, bytes: bytes.length, sha256: hash(bytes), pixelSha256: hash(decoded.data), fullSize: width === meta.width });
    imports.push(`import ${type}${width} from "./${filename}";`);
  }
  entries[type] = {
    source: { path: sourcePath, width: meta.width, height: meta.height, bytes: source.length, sha256: hash(source), pixelSha256: hash(originalPixels) },
    print: { path: printPath, bytes: print.length, sha256: hash(print) },
    variants
  };
  definitions.push(`  ${type}: { width: ${meta.width}, height: ${meta.height}, src: ${type}${widths[0]}, srcSet: [${widths.map((w) => `${type}${w} + " ${w}w"`).join(", ")}].join(", ") }`);
  console.log(`${type}: ${(source.length / 1e6).toFixed(2)} MB source -> ${variants.map((v) => `${v.width}px ${(v.bytes / 1e6).toFixed(2)} MB`).join(", ")}`);
}
const manifest = { format: "Lossless WebP", resize: "Lanczos3, aspect ratio retained, no enlargement", encoder: { sharp: sharp.versions.sharp, webp: sharp.versions.webp }, entries };
await writeFile(path.join(root, output, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
await writeFile(path.join(root, output, "artwork.generated.ts"), "// Generated by tools/encode-encounter-artwork.mjs. Preserve the approved sources.\n" + imports.join("\n") + "\n\nexport const responsiveEncounterArtwork = {\n" + definitions.join(",\n") + "\n} as const;\n");

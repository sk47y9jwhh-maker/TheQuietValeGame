"""Web versions of the poker card art (Quest and Target Cards).

The print files carry 3 mm of bleed. The web cards show the trimmed card, so
each source is cropped to the 63 x 88 mm trim (1488 x 2079 px at 600 dpi)
before it is resized. Fronts are the text-free backgrounds; the site sets the
words itself, so they stay sharp and readable. The Target front gets the three
dividers the print renderer draws.

Run from the repo root:  python3 tools/encode-card-art.py
"""
import hashlib
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src/assets/card-art"
BLEED = 71  # 3 mm at 600 dpi
TRIM = (BLEED, BLEED, 1630 - BLEED - 1, 2220 - BLEED - 1)  # 1488 x 2078
WIDTHS = (420, 840)
QUALITY = 86

SOURCES = {
    "quest-back": "design/encounter-card-templates/card-back/print/card-back-poker-gold-printerstudio-600dpi.png",
    "target-back": "design/encounter-card-templates/card-back/print/card-back-poker-silver-printerstudio-600dpi.png",
    "quest-front": "design/quest-cards/quest-front-background-600dpi.png",
    "target-front": "design/target-cards/target-front-background-600dpi.png",
}


def target_front(image: Image.Image) -> Image.Image:
    """The silver front with the print renderer's three dividers."""
    divider = Image.open(ROOT / "design/quest-cards/divider-long.png").convert("RGBA").resize((1248, 28), Image.LANCZOS)
    out = image.convert("RGBA")
    for top in (663, 905, 1648):
        out.alpha_composite(divider, (191, top))
    return out


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    manifest = {"format": f"Lossy WebP, quality {QUALITY}", "trim": "3 mm bleed removed: 1488 x 2078 px at 600 dpi", "entries": {}}
    for name, source in SOURCES.items():
        image = Image.open(ROOT / source)
        if name == "target-front":
            image = target_front(image)
        trimmed = image.convert("RGB").crop(TRIM)
        variants = []
        for width in WIDTHS:
            height = round(width * trimmed.height / trimmed.width)
            path = OUT / f"{name}-{width}.webp"
            trimmed.resize((width, height), Image.LANCZOS).save(path, "WEBP", quality=QUALITY, method=6)
            variants.append({"path": str(path.relative_to(ROOT)), "width": width, "height": height, "bytes": path.stat().st_size})
        manifest["entries"][name] = {"source": {"path": source, "sha256": sha(ROOT / source)}, "variants": variants}
    (OUT / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    lines = ["// Generated by tools/encode-card-art.py from the print files. Do not edit.\n"]
    for name in SOURCES:
        camel = "".join(part.capitalize() if i else part for i, part in enumerate(name.split("-")))
        for width in WIDTHS:
            lines.append(f'import {camel}{width} from "./{name}-{width}.webp";\n')
    lines.append("\n/** Trimmed poker card art: 1488 x 2078 at 600 dpi, so 63 x 88 mm. */\nexport const cardArt = {\n")
    for name in SOURCES:
        camel = "".join(part.capitalize() if i else part for i, part in enumerate(name.split("-")))
        lines.append(f'  {camel}: {{ src: {camel}420, srcSet: [{camel}420 + " 420w", {camel}840 + " 840w"].join(", ") }},\n')
    lines.append("} as const;\n")
    (OUT / "cardArt.generated.ts").write_text("".join(lines))
    for name, entry in manifest["entries"].items():
        print(name, [(v["width"], v["bytes"]) for v in entry["variants"]])


if __name__ == "__main__":
    main()
